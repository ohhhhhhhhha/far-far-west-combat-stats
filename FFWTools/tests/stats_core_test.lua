-- Catches filtering whole-mission points as though they were boss-only accumulated damage.
T.test("boss chart history has its own damage denominator and stops with the encounter", function()
    local s = new(); join(s, "host"); join(s, "guest")
    event(s, "covered", "coverage", 0, {sourcePlayerId = "host", metric = "damage", status = "complete", from = 0})
    event(s, "normal", "damage", 1, {sourcePlayerId = "host", targetId = "a", sourceCategory = "primary", amount = 100})
    event(s, "start", "encounter_start", 2, {encounterId = "boss"})
    local initial = s:snapshot(3)
    T.eq(initial.encounters.boss.players.host.metrics.damage, 0)
    T.eq(initial.encounters.boss.players.guest.metrics.damage, nil)
    event(s, "bossd", "damage", 4, {sourcePlayerId = "host", targetId = "b", sourceCategory = "primary", amount = 10})
    s:snapshot(5)
    event(s, "end", "encounter_end", 6, {encounterId = "boss"})
    local snap = s:snapshot(10)
    T.eq(#snap.encounters.boss.history, 3)
    T.eq(snap.encounters.boss.history[1].players.host.damage, 0)
    T.eq(snap.encounters.boss.history[2].players.host.damage, 10)
    T.eq(snap.encounters.boss.history[3].time, 6)
    T.eq(snap.encounters.boss.players.host.metrics.averageDps, 2.5)
    T.eq(#s:snapshot(20).encounters.boss.history, 3)
end)

-- Catches dropping live correlation state while restoring only already-computed totals.
