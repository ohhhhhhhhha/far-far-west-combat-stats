package.path = "FFWTools/src/FFWStats/Scripts/?.lua;FFWTools/tests/?.lua;" .. package.path
local T = require("stats_testlib")
local loaded, Stats = pcall(require, "Stats")
local function new()
    T.eq(loaded, true, "statistics module available")
    return Stats.new("mission-A")
end
local function event(s, id, kind, time, fields)
    local e = fields or {}
    e.id, e.sessionId, e.kind, e.time = id, "mission-A", kind, time
    local ok, err = s:apply(e)
    T.eq(ok, true, err)
end
local function join(s, id, time)
    event(s, "join-" .. id, "player_join", time or 0, {sourcePlayerId = id, name = id})
end
local function metric(s, playerId, name, now)
    return s:snapshot(now).players[playerId].metrics[name]
end

-- Catches using remaining target HP instead of final, overkill-inclusive damage.
T.test("final attack damage includes the entire overkill amount", function()
    local s = new(); join(s, "host")
    event(s, "hit-1", "damage", 1, {sourcePlayerId = "host", targetId = "enemy-1", amount = 1000, sourceCategory = "primary", targetRemainingHealth = 7})
    T.eq(metric(s, "host", "damage", 1), 1000)
end)

-- Catches client/server callback duplication without assuming two distinct events are equal.
T.test("the same event ID counts only once after callbacks repeat", function()
    local s = new(); join(s, "host")
    local e = {id = "attack-9", sessionId = "mission-A", kind = "damage", time = 1, sourcePlayerId = "host", amount = 65, sourceCategory = "spell", targetId = "enemy-1"}
    T.eq(s:apply(e), true)
    T.eq(s:apply(e), false)
    T.eq(metric(s, "host", "damage", 1), 65)
end)

-- Catches combat-only DPS denominators, wall-clock pauses and an inclusive old window edge.
T.test("DPS uses the supplied mission clock including noncombat and expires at five seconds", function()
    local s = new(); join(s, "host")
    event(s, "d1", "damage", 1, {sourcePlayerId = "host", amount = 100, sourceCategory = "primary", targetId = "a"})
    T.eq(metric(s, "host", "rollingDps", 5), 20)
    T.eq(metric(s, "host", "averageDps", 5), 20)
    T.eq(metric(s, "host", "rollingDps", 5), 20) -- Paused clock is unchanged.
    T.eq(metric(s, "host", "rollingDps", 6), 0)
    T.eq(metric(s, "host", "averageDps", 10), 10)
end)

-- Catches presenting unknown teammates as zero and inferring complete coverage from one hit.
T.test("unknown peer metrics stay unavailable while observed values stay partial", function()
    local s = new(); join(s, "host"); join(s, "guest")
    event(s, "d1", "damage", 1, {sourcePlayerId = "host", amount = 100, sourceCategory = "primary", targetId = "a"})
    local snap = s:snapshot(2)
    T.eq(snap.players.guest.metrics.damage, nil)
    T.eq(snap.players.guest.coverage.damage.status, "unavailable")
    T.eq(snap.players.host.coverage.damage.status, "partial")
    event(s, "coverage", "coverage", 2, {sourcePlayerId = "guest", metric = "damage", status = "complete", from = 0})
    T.eq(metric(s, "guest", "damage", 2), 0)
end)

-- Catches counting attempted damage as actual HP loss, or discarding shield absorption.
T.test("incoming damage separates health shield source and largest hit", function()
    local s = new(); join(s, "guest")
    event(s, "in1", "incoming", 1, {targetPlayerId = "guest", hpLoss = 30, shieldAbsorbed = 20, sourceCategory = "fire"})
    event(s, "in2", "incoming", 2, {targetPlayerId = "guest", hpLoss = 12, shieldAbsorbed = 0, sourceCategory = "melee"})
    local p = s:snapshot(2).players.guest
    T.eq(p.metrics.incomingDamage, 62); T.eq(p.metrics.hpLoss, 42)
    T.eq(p.metrics.shieldAbsorbed, 20); T.eq(p.metrics.largestHit, 50)
    T.eq(p.incomingBySource.fire, 50); T.eq(p.incomingBySource.melee, 12)
end)

-- Catches losing prior contributors, giving the killer an assist, or doubling game/fallback assists.
T.test("kill credit and assists retain the actual contributor identities", function()
    local s = new(); join(s, "host"); join(s, "guest")
    event(s, "d1", "damage", 1, {sourcePlayerId = "guest", targetId = "elite-1", amount = 12, sourceCategory = "dot"})
    event(s, "d2", "damage", 2, {sourcePlayerId = "host", targetId = "elite-1", amount = 100, sourceCategory = "primary"})
    event(s, "k1", "kill", 2, {sourcePlayerId = "host", targetId = "elite-1", targetClass = "elite"})
    event(s, "a1", "assist", 2, {sourcePlayerId = "guest", targetId = "elite-1"})
    event(s, "k2", "kill", 3, {sourcePlayerId = "host", targetId = "boss-1", targetClass = "boss", assistPlayerIds = {"guest"}})
    local snap = s:snapshot(3)
    T.eq(snap.players.host.metrics.kills, 2); T.eq(snap.players.host.metrics.eliteKills, 1)
    T.eq(snap.players.host.metrics.bossKills, 1); T.eq(snap.players.guest.metrics.assists, 2)
    T.eq(snap.players.guest.damageBySource.dot, 12)
end)

-- Catches crediting requested healing rather than the effective amount or mixing self/team healing.
T.test("healing and shields retain effective and overflow values", function()
    local s = new(); join(s, "host"); join(s, "guest")
    event(s, "h1", "heal", 1, {sourcePlayerId = "host", targetPlayerId = "host", amount = 100, effectiveAmount = 60})
    event(s, "h2", "heal", 2, {sourcePlayerId = "host", targetPlayerId = "guest", amount = 50, effectiveAmount = 20})
    event(s, "s1", "shield_gain", 3, {sourcePlayerId = "host", targetPlayerId = "guest", amount = 40, effectiveAmount = 25})
    local snap = s:snapshot(3)
    T.eq(snap.players.host.metrics.healing, 80); T.eq(snap.players.host.metrics.selfHealing, 60)
    T.eq(snap.players.host.metrics.teamHealing, 20); T.eq(snap.players.host.metrics.healingAttempted, 150)
    T.eq(snap.players.host.metrics.overhealing, 70); T.eq(snap.players.guest.metrics.shieldGained, 25)
    T.eq(snap.players.host.metrics.shieldGranted, 40); T.eq(snap.players.host.metrics.shieldOvergain, 15)
end)

-- Catches multiple callbacks per projectile and shotgun/DoT events inflating normal accuracy.
T.test("ordinary accuracy counts one valid hit per shot and keeps special attacks separate", function()
    local s = new(); join(s, "host")
    event(s, "shot1", "shot", 1, {sourcePlayerId = "host", attackId = "shot-A", accuracyMode = "ordinary"})
    event(s, "shot2", "shot", 1, {sourcePlayerId = "host", attackId = "shot-B", accuracyMode = "ordinary"})
    event(s, "hit1", "hit", 2, {sourcePlayerId = "host", attackId = "shot-A", validTarget = true})
    event(s, "hit2", "hit", 2, {sourcePlayerId = "host", attackId = "shot-A", validTarget = true})
    event(s, "hit3", "hit", 2, {sourcePlayerId = "host", attackId = "shot-B", validTarget = false})
    event(s, "shot3", "shot", 3, {sourcePlayerId = "host", attackId = "pellet-A", accuracyMode = "pellet"})
    event(s, "hit4", "hit", 3, {sourcePlayerId = "host", attackId = "pellet-A", validTarget = true})
    event(s, "dot1", "damage", 3, {sourcePlayerId = "host", amount = 5, sourceCategory = "dot", targetId = "enemy-3"})
    event(s, "ammo1", "ammo", 4, {sourcePlayerId = "host", amount = 3})
    event(s, "reload1", "reload", 4, {sourcePlayerId = "host"})
    local p = s:snapshot(4).players.host
    T.eq(p.metrics.shots, 2); T.eq(p.metrics.hits, 1); T.eq(p.metrics.accuracy, 0.5)
    T.eq(p.accuracyByMode.pellet.shots, 1); T.eq(p.accuracyByMode.pellet.hits, 1)
    T.eq(p.metrics.ammo, 3); T.eq(p.metrics.reloads, 1)
end)

-- Catches treating a started revive as completed and advancing completed mission time in the lobby.
T.test("completed revives and player life intervals use mission time", function()
    local s = new(); join(s, "host"); join(s, "guest")
    event(s, "down1", "down", 2, {targetPlayerId = "guest"})
    T.eq(s:apply({id = "start", sessionId = "mission-A", kind = "revive_start", time = 3, sourcePlayerId = "host", targetPlayerId = "guest"}), false)
    event(s, "rev1", "revive_complete", 5, {sourcePlayerId = "host", targetPlayerId = "guest"})
    event(s, "death1", "death", 8, {targetPlayerId = "guest"})
    event(s, "spawn1", "respawn", 10, {targetPlayerId = "guest"})
    event(s, "end", "mission_end", 12)
    local snap = s:snapshot(100)
    T.eq(snap.players.host.metrics.revives, 1); T.eq(snap.players.guest.metrics.rescued, 1)
    T.eq(snap.players.guest.metrics.downs, 1); T.eq(snap.players.guest.metrics.deaths, 1)
    T.eq(snap.players.guest.metrics.downDuration, 3); T.eq(snap.players.guest.metrics.aliveDuration, 7)
    T.eq(snap.time, 12); T.eq(snap.status, "ended")
end)

-- Catches boss-only totals accidentally replacing whole-mission damage or noncombat DPS time.
T.test("boss intervals are independent and remain included in mission totals", function()
    local s = new(); join(s, "host")
    event(s, "normal", "damage", 2, {sourcePlayerId = "host", targetId = "enemy", amount = 100, sourceCategory = "primary"})
    event(s, "boss-start", "encounter_start", 4, {encounterId = "boss-fight", name = "Boss"})
    event(s, "boss-damage", "damage", 6, {sourcePlayerId = "host", targetId = "boss", amount = 200, sourceCategory = "spell", encounterId = "boss-fight"})
    event(s, "boss-in", "incoming", 7, {targetPlayerId = "host", hpLoss = 10, shieldAbsorbed = 5, sourceCategory = "boss", encounterId = "boss-fight"})
    event(s, "boss-end", "encounter_end", 8, {encounterId = "boss-fight"})
    local snap = s:snapshot(10)
    T.eq(snap.players.host.metrics.damage, 300); T.eq(snap.players.host.metrics.averageDps, 30)
    T.eq(snap.encounters["boss-fight"].duration, 4)
    T.eq(snap.encounters["boss-fight"].players.host.metrics.damage, 200)
    T.eq(snap.encounters["boss-fight"].players.host.metrics.averageDps, 50)
    T.eq(snap.encounters["boss-fight"].players.host.metrics.incomingDamage, 15)
end)

-- Catches colour churn, fictitious points across disconnected intervals, and mutable returned snapshots.
T.test("history has stable player identity and no points across unavailable gaps", function()
    local s = new(); join(s, "host"); join(s, "guest")
    event(s, "covered", "coverage", 0, {sourcePlayerId = "guest", metric = "damage", status = "complete", from = 0})
    event(s, "d1", "damage", 1, {sourcePlayerId = "guest", amount = 20, sourceCategory = "primary", targetId = "a"})
    local first = s:snapshot(2)
    event(s, "leave", "player_leave", 3, {sourcePlayerId = "guest"})
    s:snapshot(4)
    event(s, "return", "player_join", 5, {sourcePlayerId = "guest", name = "Renamed"})
    event(s, "resumed", "coverage", 5, {sourcePlayerId = "guest", metric = "damage", status = "partial"})
    local last = s:snapshot(6)
    T.eq(last.players.guest.color, first.players.guest.color)
    T.eq(last.players.guest.metrics.damage, 20); T.eq(last.players.guest.name, "Renamed")
    T.eq(#last.history, 3); T.eq(last.history[1].players.guest.damage, 20)
    T.eq(last.history[2].players.guest, nil); T.eq(last.history[3].players.guest.damage, 20)
    T.eq(last.history[1].players.host, nil)
    T.eq(#s:snapshot(6).history, 3)
    first.players.guest.metrics.damage = 9000
    T.eq(metric(s, "guest", "damage", 6), 20)
end)

-- Catches reporting a misleading team percentage while a teammate's damage is unknown.
T.test("team shares use a complete known denominator and source shares sum to the actual damage", function()
    local s = new(); join(s, "host"); join(s, "guest")
    event(s, "d1", "damage", 1, {sourcePlayerId = "host", targetId = "a", sourceCategory = "primary", amount = 75})
    event(s, "d2", "damage", 1, {sourcePlayerId = "host", targetId = "b", sourceCategory = "spell", amount = 25})
    local partial = s:snapshot(1)
    T.eq(partial.players.host.metrics.damageShare, nil)
    T.eq(partial.team.coverage.damage.status, "partial")
    event(s, "host-covered", "coverage", 1, {sourcePlayerId = "host", metric = "damage", status = "complete", from = 0})
    event(s, "guest-covered", "coverage", 1, {sourcePlayerId = "guest", metric = "damage", status = "complete", from = 0})
    event(s, "d3", "damage", 2, {sourcePlayerId = "guest", targetId = "c", sourceCategory = "melee", amount = 50})
    local snap = s:snapshot(2)
    T.eq(snap.team.metrics.damage, 150); T.eq(snap.team.coverage.damage.status, "complete")
    T.near(snap.players.host.metrics.damageShare, 2 / 3); T.near(snap.players.guest.metrics.damageShare, 1 / 3)
    T.eq(snap.players.host.damageSourceShares.primary, 0.75); T.eq(snap.players.host.damageSourceShares.spell, 0.25)
end)

