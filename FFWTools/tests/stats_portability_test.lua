package.path='FFWTools/src/FFWStats/Scripts/?.lua;FFWTools/tests/?.lua;'..package.path
local T=require('stats_testlib');local H=require('stats_engine_harness')
local function with(options,fn)
    local h=H.new(options);local ok,err=pcall(fn,h);h:restore();assert(ok,err)
end
T.test('an unchanged panel responds to a viewport and DPI change without allocating another host',function()
    with({},function(h)
        local mod=h:load();h:key('F8');local first=mod.renderer.host
        h.width,h.height,h.dpi=1920,1080,2;mod.panel:refresh()
        T.eq(mod.renderer.host,first)
        T.eq(first.desired.X,590);T.eq(first.desired.Y,380)
    end)
end)
T.test('display settings keep nonnegative controls inside a smaller window',function()
    with({width=640,height=480,dpi=1.25},function(h)
        local mod=h:load();h:key('F8');mod.panel:mouse('toggleSettings')
        local scene=mod.renderer.lastScene
        local scale=(scene.fitScale or 1)/scene.dpiScale
        for _,c in ipairs(scene.commands) do
            T.eq(c.width>=0 and c.height>=0,true,'negative native size is invalid')
            T.eq(c.x>=0 and c.y>=0 and c.x+c.width<=scene.width+.1 and c.y+c.height<=scene.height+.1,true,'control must fit its design canvas')
        end
        T.eq(mod.renderer.host.desired.X*h.dpi<=h.width-48+.1,true)
        T.eq(mod.renderer.host.desired.Y*h.dpi<=h.height-48+.1,true)
        T.eq(scale>0,true)
    end)
end)
T.test('a minimized viewport does not build invalid geometry and can reopen after restoration',function()
    with({width=0,height=0},function(h)
        local mod=h:load();h:key('F8')
        T.eq(mod.panel.visible,true);T.eq(mod.renderer.attached,false)
        T.eq(#h.e.hosts,0,'do not allocate a native host for a zero-sized viewport')
        h.width,h.height=1280,720;mod.panel:refresh();T.eq(mod.renderer.attached,true)
    end)
end)
T.test('wall-clock correction does not freeze updates while the world real-time clock advances',function()
    with({},function(h)
        local mod=h:load();local manager=h.e.object('/Game/L_Map_Desert.Manager');manager.world=h.e.controller.world
        mod.adapter:beginMission(manager,true);h:tick(1)
        T.eq(mod.session:snapshot().time,1)
        h.wall=h.wall-3600;h:tick(6)
        T.eq(mod.session:snapshot().time,7,'use measured real-time deltas, not system-clock or frame counts')
    end)
end)
T.test('data paths are derived from each loaded module instead of a personal installation directory',function()
    local Config=require('Config')
    local a=Config.paths('@C:\\Games\\Far Far West\\ue4ss\\Mods\\FFWStats\\Scripts\\main.lua')
    local b=Config.paths('@D:/Steam 游戏/FFW/ue4ss/Mods/FFWStats/Scripts/main.lua')
    T.eq(a.save,'C:/Games/Far Far West/ue4ss/Mods/FFWStats/Data/last-mission.json')
    T.eq(b.save,'D:/Steam 游戏/FFW/ue4ss/Mods/FFWStats/Data/last-mission.json')
    T.eq(a.epoch~=b.epoch,true)
end)
T.finish()
