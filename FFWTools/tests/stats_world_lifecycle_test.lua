package.path='FFWTools/src/FFWStats/Scripts/?.lua;FFWTools/tests/?.lua;'..package.path
local T=require('stats_testlib');local H=require('stats_engine_harness')
local function with(options,fn)
    local h=H.new(options);local ok,err=pcall(fn,h);h:restore();assert(ok,err)
end
T.test('world replacement discards the old panel without calling stale reflected widget methods',function()
    with({},function(h)
        local mod=h:load();h:key('F8');local old=mod.renderer.host
        local staleCalls=0
        old.SetVisibility=function() staleCalls=staleCalls+1;error('retired native binding') end
        old.RemoveFromParent=old.SetVisibility
        for _,entry in pairs(mod.renderer.mouse.buttons) do entry.host.SetVisibility=old.SetVisibility end
        local pc=h.e.newController(false);h:controller(pc,true);h.candidates={pc}
        mod.panel:refresh()
        T.eq(staleCalls,0,'retired objects must not be touched even when IsValid still returns true')
        T.eq(mod.renderer.attached,true);T.eq(mod.renderer.controller,pc)
        T.eq(mod.renderer.host~=old,true)
    end)
end)
T.test('map load invalidates queued keys before they can construct a new-world panel',function()
    with({},function(h)
        local mod=h:load();h.keys.F8()
        T.eq(type(h.preMap),'function','entry needs the supported LoadMap lifecycle boundary')
        h.preMap();h:drain();T.eq(#h.e.hosts,0)
        h.postMap();h:tick(1);h:key('F8');T.eq(mod.renderer.attached,true)
    end)
end)
T.test('retired game hooks do not unwrap parameters or invoke callbacks after a map boundary',function()
    with({},function(h)
        local mod=h:load();local called=0
        mod.adapter:bind('/Script/Fixture:Observe',function() called=called+1 end)
        mod.adapter:registerHooks();local hook=h.e.hooks['/Script/Fixture:Observe'][1]
        local context={get=function() error('retired object was unwrapped') end}
        T.eq(type(h.preMap),'function');h.preMap()
        local ok=pcall(hook,context);T.eq(ok,true);T.eq(called,0)
        h.postMap();h:tick(1)
        ok=pcall(hook,context);T.eq(ok,true,'old callback stays retired after new world is ready')
    end)
end)
T.test('same PlayerState may acquire its real native ID after the first roster observation',function()
    with({nativeId='76561198000000002'},function(h)
        local mod=h:load();T.eq(mod.identityReady,false)
        h.members[1]['Native Net ID']='76561198000000002';h:tick(3)
        T.eq(mod.identityReady,true,'live PlayerState identity must not use a stale pawn cache')
    end)
end)
T.test('a real non-Steam Unreal ID remains unmapped and is never sent to the Steam transport',function()
    with({localRawId='EOS:synthetic-local-player'},function(h)
        local mod=h:load();mod.adapter.options.onStart('lan-world',true,true);h:tick(1);h:key('F8')
        T.eq(mod.identityReady,false);T.eq(h.sent,nil);T.eq(mod.renderer.attached,true)
        T.eq(mod.captureStatus.reason,'unmapped_roster_id','UI exposes the specific missing identity condition')
    end)
end)
T.test('an authoritative local controller identifies the host when the game flag is not initialized',function()
    with({},function(h)
        h.members[1].isHost=false;local mod=h:load()
        T.eq(mod.identityReady,true)
        T.eq(mod.session.localId,mod.session.hostId)
    end)
end)
T.test('ambiguous local controllers revoke the previous world before any further capture',function()
    with({},function(h)
        local mod=h:load();local manager=h.e.object('/Game/L_Map_Desert.Manager');manager.world=h.e.controller.world
        mod.adapter:beginMission(manager,true);T.eq(mod.identityReady,true)
        local duplicate=h:controller(h.e.object('TransitionLocalController'),true);duplicate.world=h.e.object('NextWorld')
        h.candidates={h.e.controller,duplicate};h:tick(1)
        T.eq(mod.identityReady,false);T.eq(mod.adapter.active,false)
        T.eq(next(mod.session.sync.roster),nil)
    end)
end)
T.test('conflicting host flags never select the last roster row as authority',function()
    with({},function(h)
        h.members[2]=h:player('76561198000000002',true)
        local mod=h:load();T.eq(mod.identityReady,false)
        T.eq(mod.captureStatus.reason,'ambiguous_host');T.eq(h.sent,nil)
    end)
end)
T.finish()
