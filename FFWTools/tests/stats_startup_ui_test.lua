package.path='FFWTools/src/FFWStats/Scripts/?.lua;FFWTools/tests/?.lua;'..package.path
local T=require('stats_testlib');local H=require('stats_engine_harness')
local function with(options,fn)
    local h=H.new(options);local ok,err=pcall(fn,h);h:restore();assert(ok,err)
end
T.test('F8 reaches a locally owned empty panel when the first controller belongs to a remote player',function()
    with({remoteFirst=true,emptyRoster=true,nativeReady=false},function(h)
        local mod=h:load();h:key('F8')
        T.eq(mod.panel.visible,true);T.eq(mod.renderer.attached,true,'F8 must attach without a trusted statistics identity')
        T.eq(mod.renderer.controller,h.e.controller);T.eq(mod.renderer.host.onScreen,true)
    end)
end)
T.test('F8 loads its own host and font before another mod has opened a card panel',function()
    with({assetsLoaded=false,emptyRoster=true,nativeReady=false},function(h)
        local mod=h:load();h:key('F8');T.eq(mod.renderer.attached,true)
        T.eq(h.loaded,true);T.eq(mod.panel:model().message~=nil,true)
    end)
end)
T.test('a queued F8 callback cannot build native widgets after the component is stopped',function()
    with({},function(h)
        local mod=h:load();h.keys.F8();mod.stop();h:drain()
        T.eq(#h.e.hosts,0,'queued input is cancelled before constructing a host')
    end)
end)
T.test('failed boot epoch persistence is retried before admitting any synchronized mission',function()
    with({epochWritable=false},function(h)
        local mod=h:load();h.adapter=mod.adapter
        h.adapter.options.onStart('world-a',true,true);h:tick(1)
        T.eq(mod.session.phase,'lobby');T.eq(h.sent,nil)
        h:key('F8');T.eq(mod.renderer.attached,true)
        h.epochWritable=true;h:tick(3)
        T.eq(mod.session.phase,'active','writable Data recovers without restarting the game')
    end)
end)
T.test('bridge API arriving after Lua startup is discovered without blocking UI',function()
    with({bridge=false},function(h)
        local mod=h:load();mod.adapter.options.onStart('world-a',true,true)
        h:key('F8');T.eq(mod.renderer.attached,true)
        h.env.FFWTeamSync=h.transport;h:tick(3)
        T.eq(mod.session.phase,'active','late native API must be refreshed')
    end)
end)
T.test('a delayed native Steam identity starts a partially observed mission after verification',function()
    with({nativeReady=false},function(h)
        local mod=h:load();mod.adapter.options.onStart('world-a',true,true);h:key('F8')
        T.eq(mod.captureStatus.reason,'native_identity_pending');T.eq(mod.session.phase,'lobby')
        h.nativeReady=true;h:tick(3)
        T.eq(mod.session.phase,'active');T.eq(mod.session.fresh,false)
        T.eq(mod.captureStatus.reason,'ready')
    end)
end)
T.finish()
