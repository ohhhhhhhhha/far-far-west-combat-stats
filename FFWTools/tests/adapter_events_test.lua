package.path='FFWTools/src/FFWStats/Scripts/?.lua;'..package.path
local T=dofile('FFWTools/tests/stats_testlib.lua')
local E=require('Events')
T.test('only authoritative mission damage is accepted, with verified player ownership',function()
    T.eq(E.enemyDamage({active=true,authority=false,sourcePlayerId='a',amount=20}),nil)
    T.eq(E.enemyDamage({active=false,authority=true,sourcePlayerId='a',amount=20}),nil)
    T.eq(E.enemyDamage({active=true,authority=true,amount=20}),nil)
end)
T.test('final overkill value is preserved independently of negative remaining HP',function()
    local e=assert(E.enemyDamage({active=true,authority=true,sourcePlayerId='b',targetId='enemy1',amount=1000,health=-995,category='primary'}))
    T.eq(e.amount,1000);T.eq(e.sourcePlayerId,'b');T.eq(e.sourceCategory,'primary')
end)
T.test('shield settlement counts absorbed shield and actual HP loss without overkill incoming',function()
    local e=assert(E.incoming({targetPlayerId='a',currentPlayerHeal=20,damages=100,outputHeal=85,isTutorial=false,sourceCategory='enemy'}))
    T.eq(e.hpLoss,20);T.eq(e.shieldAbsorbed,15)
    local shield=assert(E.incoming({targetPlayerId='a',currentPlayerHeal=20,damages=8,outputHeal=0}))
    T.eq(shield.hpLoss,0);T.eq(shield.shieldAbsorbed,8)
end)
T.test('tutorial health floor and fully absorbed boundary use game settlement outputs',function()
    local e=assert(E.incoming({targetPlayerId='a',currentPlayerHeal=20,damages=20,outputHeal=20,isTutorial=true}))
    T.eq(e.hpLoss,19);T.eq(e.shieldAbsorbed,0)
end)
T.test('different damage source categories never use element alone as proof of DoT',function()
    T.eq(E.sourceCategory({itemName='rifle',primary='rifle',secondary='pistol',element=8}),'primary')
    T.eq(E.sourceCategory({itemName='pistol',primary='rifle',secondary='pistol',element=1}),'secondary')
    T.eq(E.sourceCategory({itemName='flame',spells={flame=true},element=8}),'spell')
    T.eq(E.sourceCategory({itemName='flame',spells={flame=true},verifiedDot=true}),'dot')
    T.eq(E.sourceCategory({element=4}),'melee')
    T.eq(E.sourceCategory({element=8}),'unknown')
end)
T.test('verified game item categories work without a replicated loadout',function()
    local a=require('GameAdapter').new({});a.players.p={}
    for _,name in ipairs({'itemLongRanger','itemShotgun','itemWinchester','itemKnuckles','itemLasso','itemMinigun','itemQuadCylinder'}) do
        T.eq(a:category('p',name,1,false),'primary')
    end
    for _,name in ipairs({'itemPistol','itemDualRevolver','itemBoomerang','itemBow','itemSheriffStar','itemBanjo','itemJetpack'}) do
        T.eq(a:category('p',name,1,false),'secondary')
    end
    for _,name in ipairs({'itemFire','itemIce','itemAcid','itemElec','itemCactus','itemVoodoo'}) do
        T.eq(a:category('p',name,nil,false),'spell')
    end
    T.eq(a:category('p','ITEMLONGRANGER',8,false),'primary','FName identity is case insensitive')
    T.eq(a:category('p','itemMelee',4,false),'melee')
    T.eq(a:category('p','itemFire',8,true),'dot')
    T.eq(a:category('p','unverifiedItem',8,false),'unknown')
end)
T.test('healing attribution needs a known source and separates overflow',function()
    T.eq(E.heal({targetPlayerId='a',amount=100,effectiveAmount=20}),nil)
    local e=assert(E.heal({sourcePlayerId='b',targetPlayerId='a',amount=100,effectiveAmount=20}))
    T.eq(e.amount,100);T.eq(e.effectiveAmount,20)
end)
T.test('observed HP subtraction rounding does not discard a real 1.2 heal',function()
    local e=assert(E.heal({sourcePlayerId='a',targetPlayerId='a',amount=1.2,effectiveAmount=1.2000000000000028}))
    T.eq(e.effectiveAmount,1.2)
    T.eq(E.heal({sourcePlayerId='a',targetPlayerId='a',amount=1.2,effectiveAmount=1.3}),nil)
end)
T.finish()
