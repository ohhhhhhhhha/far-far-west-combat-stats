package.path='FFWTools/src/FFWStats/Scripts/?.lua;'..package.path
local T=dofile('FFWTools/tests/stats_testlib.lua')
local Buffer=require('EventBuffer')
local function hit(target,owner,amount,item,element)
    return {kind='damage',targetId=target,sourcePlayerId=owner,amount=amount,sourceCategory='unknown'},
        {item=item or 'gun',element=element or 1}
end
local function damage(b,target,owner,amount,time,stamp,item,element)
    local event,meta=hit(target,owner,amount,item,element)
    b:damage(event,time,stamp,meta);return event
end
local function settled(b,target,owner,category,stamp,item,element)
    b:settlement(target,stamp,{owner=owner,category=category,item=item or 'gun',element=element or 1})
end
local function drain(b)
    local r={};b:flush(function(e,t,own) r[#r+1]={event=e,time=t,own=own} end);return r
end
T.test('post settlement keeps final damage including overkill',function()
    local b=Buffer.new();damage(b,'enemy','a',183.75,1,100)
    settled(b,'enemy','a','primary',100)
    local r=drain(b);T.eq(#r,1);T.eq(r[1].event.amount,183.75);T.eq(r[1].event.sourceCategory,'primary')
end)
T.test('nested posts use LIFO and preserve the original event order',function()
    local b=Buffer.new();damage(b,'enemy','a',50,1,100);damage(b,'enemy','a',2,1,100)
    settled(b,'enemy','a','dot',100);settled(b,'enemy','a','primary',100)
    local r=drain(b);T.eq(r[1].event.sourceCategory,'primary');T.eq(r[2].event.sourceCategory,'dot')
end)
T.test('extra invulnerable call makes the whole ambiguous group unknown',function()
    local b=Buffer.new();damage(b,'enemy','a',50,1,100)
    settled(b,'enemy','a','dot',100);settled(b,'enemy','a','primary',100)
    local r=drain(b);T.eq(r[1].event.sourceCategory,'unknown');T.eq(r[1].event.amount,50)
end)
T.test('unmatched multicast or mismatched owner cannot borrow another source',function()
    local b=Buffer.new();damage(b,'enemy','a',50,1,100);settled(b,'enemy','b','dot',100)
    damage(b,'other','a',7,1,100)
    local r=drain(b);T.eq(r[1].event.sourceCategory,'unknown');T.eq(r[2].event.sourceCategory,'unknown')
end)
T.test('item and element must both match',function()
    local b=Buffer.new();damage(b,'one','a',50,1,100);settled(b,'one','a','dot',100,'spell')
    damage(b,'two','a',50,1,100);settled(b,'two','a','dot',100,'gun',2)
    for _,r in ipairs(drain(b)) do T.eq(r.event.sourceCategory,'unknown') end
end)
T.test('same target on different engine timestamps does not cross-pair',function()
    local b=Buffer.new();damage(b,'enemy','a',50,1,100);settled(b,'enemy','a','dot',101)
    T.eq(drain(b)[1].event.sourceCategory,'unknown')
end)
T.test('damage remains before kill and local attack events keep their timestamp',function()
    local b=Buffer.new();damage(b,'enemy','a',50,1,100)
    b:push({kind='kill'},1,false);settled(b,'enemy','a','primary',100)
    b:push({kind='shot'},1.1,true)
    local r=drain(b);T.eq(r[1].event.kind,'damage');T.eq(r[2].event.kind,'kill')
    T.eq(r[3].time,1.1);T.eq(r[3].own,true);T.eq(#drain(b),0)
end)
T.test('bad group does not invalidate an unrelated enemy',function()
    local b=Buffer.new();damage(b,'one','a',3,1,100);settled(b,'one','b','dot',100)
    damage(b,'two','a',4,1,100);settled(b,'two','a','secondary',100)
    local r=drain(b);T.eq(r[1].event.sourceCategory,'unknown');T.eq(r[2].event.sourceCategory,'secondary')
end)
T.test('a weak paired input does not erase the final feedback source',function()
    local b=Buffer.new();local event=damage(b,'enemy','a',50,1,100)
    event.sourceCategory='secondary';settled(b,'enemy','a','unknown',100)
    T.eq(drain(b)[1].event.sourceCategory,'secondary')
end)
T.finish()
