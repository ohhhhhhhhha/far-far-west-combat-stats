package.path='FFWTools/src/FFWStats/Scripts/?.lua;'..package.path
local T=dofile('FFWTools/tests/stats_testlib.lua')
local Stats,Store,Session=require('Stats'),require('Store'),require('Session')
local path='FFWTools/tests/session-lifecycle.json'
local transport={channel=4605527,maxPayload=262144,localSteamId=function() return 'host' end,
    poll=function() end,send=function() return true end,close=function() return true end}
local roster={host={playerId='host',name='房主',isHost=true}}
local function fresh()
    local s=Session.new({path=path,epoch=100,transport=transport,verifiedHostMetrics={'damage'}})
    s:setRoster(roster,'host','host',0);return s
end
T.test('lobby boot displays previous data without replacing it',function()
    local old=Stats.new('old')
    assert(old:apply({id='j',sessionId='old',kind='player_join',sourcePlayerId='host',time=0}))
    assert(old:apply({id='d',sessionId='old',kind='damage',sourcePlayerId='host',targetId='enemy',amount=183.75,sourceCategory='primary',time=1}))
    assert(Store.write(path,old:snapshot(5)))
    local s=fresh();s:tick(10,0)
    T.eq(s:snapshot().sessionId,'old');T.eq(s:snapshot().players.host.metrics.damage,183.75)
    T.eq(Store.read(path).sessionId,'old')
end)
T.test('only a distinct explicit mission resets once',function()
    local s=fresh();assert(s:begin('world-1',true,true))
    assert(s:ingest({kind='damage',sourcePlayerId='host',targetId='enemy',amount=183.75,sourceCategory='primary'},1,false))
    T.eq(s:begin('world-1',true,true),false)
    s:tick(11,5);T.eq(s:snapshot().players.host.metrics.damage,183.75)
    local first=s:snapshot().sessionId
    assert(s:begin('world-2',true,true));s:tick(12,0)
    T.eq(s:snapshot().players.host.metrics.damage,0)
    T.eq(s:snapshot().sessionId==first,false)
end)
T.test('solo mission freezes on end and survives application restart',function()
    local s=fresh();s:begin('world-3',true,true)
    assert(s:ingest({kind='damage',sourcePlayerId='host',targetId='enemy',amount=250,sourceCategory='primary'},1,false))
    s:finish(10);s:tick(20,10);s:tick(30,999)
    T.eq(s:snapshot().time,10);T.eq(s:snapshot().status,'ended')
    T.eq(fresh():snapshot().players.host.metrics.damage,250)
end)
local paths={path}
local function pair()
    local queues={host={},guest={}}
    local members={host={playerId='host',name='房主',isHost=true},guest={playerId='guest',name='队友'}}
    local function endpoint(id)
        return {channel=4605527,maxPayload=262144,localSteamId=function() return id end,
            send=function(peer,_,bytes) queues[peer][#queues[peer]+1]={id,bytes};return true end,
            poll=function() local p=table.remove(queues[id],1);if p then return table.unpack(p) end end,
            close=function() return true end}
    end
    local function make(id,epoch)
        local filename='FFWTools/tests/session-lifecycle-'..id..'.json';paths[#paths+1]=filename
        local s=Session.new({path=filename,epoch=epoch,transport=endpoint(id),localTracking={reload=true}})
        s:setRoster(members,id,'host',0);return s
    end
    for _,id in ipairs({'host','guest'}) do
        local filename='FFWTools/tests/session-lifecycle-'..id..'.json'
        os.remove(filename);os.remove(filename..'.bak');os.remove(filename..'.tmp')
    end
    local h,g=make('host',200),make('guest',300)
    local function cycle(wall,time)
        h:tick(wall,time);g:tick(wall,time);h:tick(wall,time);g:tick(wall,time)
    end
    return h,g,cycle,make,queues
end
T.test('a fresh guest mission refuses delayed previous host hello before submitting new events',function()
    local h,g,cycle=pair()
    h:begin('world-a',true,true);g:begin('world-a',true,false);cycle(0,0)
    local prior=h.sessionId
    assert(g:begin('world-b',true,false))
    assert(g:ingest({kind='reload',sourcePlayerId='guest'},0,true))
    cycle(2,1)
    T.eq(g.sync.bound,false,'old hello must not bind the new mission')
    T.eq(g:snapshot(),nil,'old data must not reappear as the new mission')
    T.eq(h.run:snapshot(1).players.guest.metrics.reloads,0,'new reload stays out of the old mission')
    h:begin('world-b',true,true);cycle(3,0);cycle(4,1)
    T.eq(g.sessionId==prior,false);T.eq(g.sync.bound,true)
    T.eq(h.run:snapshot(1).players.guest.metrics.reloads,1)
end)
T.test('fresh guest mission after restart also gates the saved previous session',function()
    local h,g,cycle,make=pair()
    h:begin('world-a',true,true);g:begin('world-a',true,false);cycle(0,0)
    assert(g:publish())
    local restarted=make('guest',301)
    restarted:begin('world-b',true,false)
    h:tick(2,1);restarted:tick(2,0)
    T.eq(restarted.sync.bound,false)
    T.eq(restarted:snapshot(),nil)
end)
T.test('same mission guest restart replays its unacknowledged event exactly once',function()
    local h,g,cycle,make=pair()
    h:begin('world-a',true,true);g:begin('world-a',true,false);cycle(0,0)
    assert(g:ingest({kind='reload',sourcePlayerId='guest'},1,true))
    assert(g:publish())
    local resumed=make('guest',301)
    resumed:begin('world-a',false,false)
    for wall=1,4 do h:tick(wall,wall);resumed:tick(wall,wall) end
    h:tick(5,5);resumed:tick(5,5)
    T.eq(h.run:snapshot(5).players.guest.metrics.reloads,1)
    T.eq(resumed.sync:status().pendingEvents,0)
    T.eq(resumed.sessionId,h.sessionId)
end)
T.test('host resumes an active matching world without resetting totals or its mission clock',function()
    local s=fresh();s:begin('resume-world',true,true)
    assert(s:ingest({kind='damage',sourcePlayerId='host',targetId='one',amount=100,sourceCategory='primary'},1,false))
    s:tick(5,5);assert(s:publish())
    local id=s.sessionId
    local resumed=Session.new({path=path,epoch=101,transport=transport})
    resumed:setRoster(roster,'host','host',0)
    resumed:begin('resume-world',false,true)
    assert(resumed:ingest({kind='damage',sourcePlayerId='host',targetId='two',amount=40,sourceCategory='primary'},1,false))
    resumed:tick(1,1)
    T.eq(resumed:snapshot().sessionId,id)
    T.eq(resumed:snapshot().time,6)
    T.eq(resumed:snapshot().players.host.metrics.damage,140)
    T.eq(resumed:snapshot().players.host.coverage.damage.status,'partial','restart leaves an unobserved interval')
end)
T.test('the panel refreshes every second while disk writes remain five seconds apart',function()
    os.remove(path);os.remove(path..'.bak')
    local shown={}
    local s=Session.new({path=path,epoch=400,transport=transport,onSnapshot=function(snapshot,display) shown[#shown+1]={snapshot,display} end})
    s:setRoster(roster,'host','host',0);s:begin('display-world',true,true);s:tick(0,0)
    assert(s:ingest({kind='damage',sourcePlayerId='host',targetId='enemy',amount=183.75,sourceCategory='primary'},0.5,false))
    s:tick(1,1)
    T.eq(shown[#shown][1].players.host.metrics.damage,183.75)
    T.eq(Store.read(path).players.host.metrics.damage,nil,'one second update must not cause a disk write')
    s:tick(5,5)
    T.eq(Store.read(path).players.host.metrics.damage,183.75)
end)
T.test('a retained active save is shown as previous until an actual mission begins',function()
    local shown
    local s=Session.new({path=path,epoch=401,transport=transport,onSnapshot=function(snapshot,display) shown={snapshot,display} end})
    T.eq(shown[1].players.host.metrics.damage,183.75)
    T.eq(shown[2].previous,true)
    s:tick(999,0)
    T.eq(s:snapshot().time,5,'lobby wall clock cannot advance last mission')
end)
T.test('a guest that finishes before binding sends its finish watermark after the hello',function()
    local h,g,cycle=pair()
    h:begin('world-a',true,true);g:begin('world-a',true,false)
    g:finish(1);h:finish(1);cycle(0,1);cycle(1,1)
