    T.eq(g.sync:finishStatus().acknowledged,true)
end)
T.test('a disconnected guest rejoins the ongoing mission and reopens its local event stream',function()
    local h,g,cycle=pair()
    h:begin('world-a',true,true);g:begin('world-a',true,false);cycle(0,0)
    g:finish(1);cycle(1,1);assert(g:publish())
    g.options.nextEpoch=function() return 301 end
    assert(g:begin('rejoined-client-world',false,false))
    cycle(2,2)
    T.eq(g.sync.bound,true,'same active authority session remains eligible after disconnect')
    T.eq(g.sessionId,h.sessionId)
    assert(g:ingest({kind='reload',sourcePlayerId='guest'},1,true))
    cycle(3,3)
    T.eq(h.run:snapshot(3).players.guest.metrics.reloads,1)
end)
T.test('a known fresh mission observed late cannot claim complete coverage',function()
