    T.eq(g.sessionId,h.sessionId)
    T.eq(h.run:snapshot(1).players.guest.metrics.reloads,0,'candidate A event cannot enter B totals')
end)
T.test('a fresh next-mission waiting queue survives reconnect without entering the previous mission',function()
    local h,g,cycle=pair()
    h:begin('world-a',true,true);g:begin('world-a',true,false);cycle(0,0)
    g:begin('world-b',true,false)
    assert(g:ingest({kind='reload',sourcePlayerId='guest'},1,true))
    g:finish(1);g:begin('world-b-reconnect',false,false)
    cycle(2,1);T.eq(g.sync.bound,false)
    T.eq(h.run:snapshot(1).players.guest.metrics.reloads,0)
    h:begin('world-b',true,true);cycle(3,0);cycle(4,1)
    T.eq(h.run:snapshot(1).players.guest.metrics.reloads,1)
end)
T.test('host-first next mission hello remains eligible when the guest observes its local start later',function()
    local h,g,cycle=pair()
    h:begin('world-a',true,true);g:begin('world-a',true,false);cycle(0,0)
    local old=h.sessionId
    g:finish(1);h:finish(1);cycle(1,1);cycle(2,1);g:refresh()
    T.eq(g:snapshot().status,'ended')
    h:begin('world-b',true,true);cycle(3,0)
    T.eq(g.sessionId,old,'future hello cannot change the local finished lifecycle')
    g:begin('world-b',true,false);cycle(4,1);cycle(5,2)
    T.eq(g.sync.bound,true)
    T.eq(g.sessionId,h.sessionId)
    assert(g:ingest({kind='reload',sourcePlayerId='guest'},2,true));cycle(6,3)
    T.eq(h.run:snapshot(3).players.guest.metrics.reloads,1)
end)
T.test('a delayed local end for A cannot send a finish watermark for an early authority B',function()
    local h,g,cycle=pair()
    h:begin('world-a',true,true);g:begin('world-a',true,false);cycle(0,0)
    h:begin('world-b',true,true);cycle(2,0)
    g:finish(1);h:tick(3,1)
    T.eq(h.sync:finishStatus().peers.guest.lastSequence,nil,'B must not receive the old local end')
end)
