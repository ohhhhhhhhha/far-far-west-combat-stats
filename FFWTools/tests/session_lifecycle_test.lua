end)
T.test('two reconnects before the host hello retain one local event for the same mission',function()
    local h,g,cycle=pair()
    h:begin('world-a',true,true);g:begin('world-a',true,false);cycle(0,0)
    g.options.nextEpoch=function() return g.epoch+1 end
    g:finish(1);assert(g:begin('reconnect-1',false,false))
    assert(g:ingest({kind='reload',sourcePlayerId='guest'},1,true))
    g:finish(1);assert(g:begin('reconnect-2',false,false))
    cycle(2,2);cycle(3,3)
    T.eq(h.run:snapshot(3).players.guest.metrics.reloads,1)
    T.eq(g.sync:status().pendingEvents,0)
end)
T.test('unbound local events persist with a real retained snapshot and survive a boot',function()
    local h,g,cycle,make=pair()
    h:begin('world-a',true,true);g:begin('world-a',true,false);cycle(0,0)
    g.options.nextEpoch=function() return 301 end
    g:finish(1);g:begin('reconnect-1',false,false)
    assert(g:ingest({kind='reload',sourcePlayerId='guest'},1,true))
    T.eq(g:publish(),true,'unbound queue must reach the paired save file')
    T.eq(g:snapshot(),nil,'retained save must not masquerade as a newly received snapshot')
    local resumed=make('guest',302);resumed:begin('reconnect-2',false,false)
    for wall=2,4 do h:tick(wall,wall);resumed:tick(wall,wall);h:tick(wall,wall);resumed:tick(wall,wall) end
    T.eq(h.run:snapshot(4).players.guest.metrics.reloads,1)
    T.eq(resumed.sync:status().pendingEvents,0)
end)
T.test('events queued for a reconnect candidate are discarded when the host confirms another mission',function()
    local h,g,cycle=pair()
    h:begin('world-a',true,true);g:begin('world-a',true,false);cycle(0,0)
    g.options.nextEpoch=function() return 301 end
    g:finish(1);g:begin('reconnect-1',false,false)
    assert(g:ingest({kind='reload',sourcePlayerId='guest'},1,true))
