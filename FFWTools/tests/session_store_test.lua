package.path='FFWTools/src/FFWStats/Scripts/?.lua;'..package.path
local T=dofile('FFWTools/tests/stats_testlib.lua')
local Stats,Store=require('Stats'),require('Store')
local path='FFWTools/tests/session-pair-test.json'
T.test('one disk replacement pairs a snapshot with its acknowledged transport watermark',function()
    local s=Stats.new('mission-a')
    assert(s:apply({id='j',sessionId='mission-a',kind='player_join',sourcePlayerId='a',time=0}))
    assert(s:apply({id='d',sessionId='mission-a',kind='damage',sourcePlayerId='a',targetId='enemy',amount=183.75,sourceCategory='primary',time=1}))
    assert(Store.write(path,s:snapshot(2),{sessionId='mission-a',peers={b={eventSequence=8}},localEpoch=30}))
    local snapshot,_,checkpoint=Store.read(path)
    T.eq(snapshot.players.a.metrics.damage,183.75)
    T.eq(checkpoint.peers.b.eventSequence,8)
    T.eq(checkpoint.sessionId,snapshot.sessionId)
end)
T.test('snapshot without a transport checkpoint remains backward compatible',function()
    assert(Store.write(path,Stats.new('offline'):snapshot(0)))
    local snapshot,_,checkpoint=Store.read(path)
    T.eq(snapshot.sessionId,'offline');T.eq(checkpoint,nil)
end)
os.remove(path);os.remove(path..'.tmp');os.remove(path..'.bak')
T.finish()
